# builder_status.py
"""
Модуль для работы со статусами строителей в игре.
Функционал:
- Определение текущего статуса строителей
- Ожидание освобождения строителей
- Проверка занятости всех строителей
"""

import time
from utils import find_on_screen
from logger import log
from config import CONFIDENCE_BUILDER

# Константы модуля
IMAGE_DIR = "C:/farmbot/images/"  # Путь к директории с изображениями статусов

def get_builder_status():
    """
    Определяет текущий статус строителей по изображению на экране.
    
    Проверяет наличие изображений статусов и возвращает соответствующий код:
    - '0_2' - все строители заняты
    - '1_2' - свободен 1 из 2 строителей
    - '2_2' - все строители свободны
    - 'unknown' - статус не определен
    
    Returns:
        str: Код статуса строителей или 'unknown' если статус не распознан
    """
    # Перебираем возможные статусы строителей
    for status_img in ["0_2.png", "1_2.png", "2_2.png"]:
        full_path = IMAGE_DIR + status_img
        # Поиск изображения на экране с учетом:
        # - Уровня уверенности распознавания из конфига
        # - Ожидаемости ошибок (не логируем если не найдено)
        found = find_on_screen(full_path, 
                             confidence=CONFIDENCE_BUILDER,
                             is_expected_fail=True)
        if found:
            # Возвращаем название файла без расширения
            return status_img.replace(".png", "")
    return "unknown"  # Статус не распознан

def wait_for_free_builder(timeout=300):
    """
    Ожидает освобождения хотя бы одного строителя в течение заданного времени.
    
    Args:
        timeout (int): Максимальное время ожидания в секундах (по умолчанию 300)
    
    Returns:
        bool: True если хотя бы один строитель освободился, False если время истекло
    """
    log("⏳ Ожидаем свободного строителя...")
    start = time.time()
    
    # Цикл проверки статуса с интервалом 5 секунд
    while time.time() - start < timeout:
        status = get_builder_status()
        
        # Проверяем наличие свободных строителей (1 или 2 из 2)
        if status in ["2_2", "1_2"]:
            log(f"✅ Найден свободный строитель ({status})")
            return True
            
        time.sleep(5)  # Пауза между проверками
    
    # Если время ожидания истекло
    log("❌ Строители не освободились в течение времени ожидания.")
    return False

def builders_busy():
    """
    Проверяет, заняты ли все строители.
    
    Returns:
        bool: True если все строители заняты (статус '0_2'), иначе False
    """
    status = get_builder_status()
    # Явная проверка на статус "все заняты"
    return status == "0_2"