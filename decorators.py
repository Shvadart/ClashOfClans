# decorators.py
"""
Модуль декораторов для игрового бота. Содержит:
- Декоратор для автоматического сбора ресурсов перед выполнением функций
"""

from functools import wraps
from collect import collect_resources_if_visible
from logger import log
from utils import debug_screenshot
import time

def with_resource_collection(func):
    """
    Декоратор для автоматического сбора ресурсов перед выполнением функции.
    
    Основные функции:
    1. Автоматически собирает видимые ресурсы перед выполнением декорируемой функции
    2. Обрабатывает ошибки сбора ресурсов
    3. Сохраняет отладочную информацию при ошибках
    
    Args:
        func (callable): Функция, которую нужно декорировать
        
    Returns:
        callable: Обернутая функция с функционалом сбора ресурсов
    """
    @wraps(func)  # Сохраняем метаданны оригинальной функции
    def wrapper(*args, **kwargs):
        """
        Обертка вокруг декорируемой функции.
        Выполняет сбор ресурсов перед вызовом основной функции.
        
        Args:
            *args: Позиционные аргументы для декорируемой функции
            **kwargs: Именованные аргументы для декорируемой функции
            
        Returns:
            Результат выполнения декорируемой функции
            
        Raises:
            KeyboardInterrupt: Если пользователь прервал выполнение
            Exception: Любые другие ошибки с дополнительной информацией
        """
        try:
            # 1. Пытаемся собрать ресурсы
            collect_resources_if_visible()
            
            # 2. Короткая пауза для стабилизации игрового клиента
            time.sleep(0.5)
            
            # 3. Выполняем основную функцию
            return func(*args, **kwargs)
            
        except KeyboardInterrupt:
            # Обработка прерывания пользователем
            log("⏹ Сбор ресурсов прерван пользователем")
            raise  # Пробрасываем исключение дальше
            
        except Exception as e:
            # Обработка других ошибок с сохранением отладочной информации
            log(f"❌ Ошибка при сборе ресурсов: {str(e)}")
            debug_screenshot()  # Сохраняем скриншот для диагностики
            raise  # Пробрасываем исключение дальше
            
    return wrapper